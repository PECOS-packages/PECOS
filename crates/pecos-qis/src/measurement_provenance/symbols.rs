pub fn policy(symbol: &str) -> Policy {
    let name = symbol.trim_start_matches('@').trim_matches('"');
    SYMBOLS
        .iter()
        .find(|(names, _, _)| names.contains(&name))
        .map_or(Policy::Unknown, |(_, p, _)| *p)
}
